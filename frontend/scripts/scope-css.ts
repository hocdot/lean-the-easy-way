// Writes src/verso/widgets.css: the site's stylesheet with every rule limited to `.lfa`
// (the boxes the question widgets render into), so it cannot restyle Verso's own pages.
// Page-wide rules (body, html) are dropped; theme tokens move from :root onto .lfa.
import { readFileSync, writeFileSync } from 'node:fs'

const src = readFileSync(new URL('../src/styles.css', import.meta.url), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '')

function scopeSelector(sel: string): string | null {
  const s = sel.trim()
  if (!s) return null
  if (/^(html|body)\b/.test(s) || s === 'html, body') return null
  // theme tokens: on the widget box, following the page's data-theme (set by the theme switch)
  if (s === ':root') return '.lfa'
  if (s.startsWith(':root:not(')) return `${s} .lfa`
  if (s.startsWith(':root[')) return `${s} .lfa`
  if (s === '*') return '.lfa, .lfa *'
  return `.lfa ${s}`
}

function scope(css: string): string {
  let out = ''
  let i = 0
  while (i < css.length) {
    const open = css.indexOf('{', i)
    if (open < 0) break
    const head = css.slice(i, open).trim()
    // find the matching close brace
    let depth = 1
    let j = open + 1
    while (j < css.length && depth) {
      if (css[j] === '{') depth++
      else if (css[j] === '}') depth--
      j++
    }
    const body = css.slice(open + 1, j - 1)
    if (head.startsWith('@media') || head.startsWith('@supports')) {
      const inner = scope(body)
      if (inner.trim()) out += `${head} {\n${inner}}\n`
    } else if (head.startsWith('@keyframes') || head.startsWith('@font-face')) {
      out += `${head} {${body}}\n`
    } else {
      const sels = head.split(',').map(scopeSelector).filter((x): x is string => !!x)
      if (sels.length) out += `${sels.join(', ')} {${body}}\n`
    }
    i = j
  }
  return out
}

const scoped = `/* generated by scripts/scope-css.ts from src/styles.css: do not edit */\n.lfa { font: 15px/1.6 var(--font-ui); color: var(--ink); }\n${scope(src)}`
writeFileSync(new URL('../src/verso/widgets.css', import.meta.url), scoped)
console.log(`wrote src/verso/widgets.css (${scoped.length} bytes)`)
